#!/usr/bin/env node
// Bundles the Markdown, JSON, and HTML under studio/ into src/studio-pack.js so the server can serve
// the Video Studio pack on Node and on Cloudflare Workers (no fs at runtime). Fonts stay as files.
//   node scripts/build-studio-pack.mjs          write src/studio-pack.js
//   node scripts/build-studio-pack.mjs --check  exit 1 if src/studio-pack.js is stale
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const studio = path.join(root, 'studio');
const out = path.join(root, 'src', 'studio-pack.js');
const TEXT = new Set(['.md', '.json', '.html', '.txt']);

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((entry) => {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) return walk(full);
      return (TEXT.has(path.extname(entry.name)) || entry.name === 'LICENSE') && !entry.name.startsWith('OFL') ? [full] : [];
    });
}

export function buildPack() {
  const files = {};
  for (const file of walk(studio)) {
    files[path.relative(studio, file).split(path.sep).join('/')] = fs.readFileSync(file, 'utf8');
  }
  return `// Generated by scripts/build-studio-pack.mjs from studio/. Do not edit by hand.\nexport const STUDIO_FILES = ${JSON.stringify(files, null, 0)};\n`;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const text = buildPack();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (current !== text) {
      console.error('src/studio-pack.js is stale. Run: node scripts/build-studio-pack.mjs');
      process.exit(1);
    }
  } else {
    fs.writeFileSync(out, text);
    console.log(`Wrote ${path.relative(root, out)} (${Object.keys(JSON.parse(text.slice(text.indexOf('{'), text.lastIndexOf('}') + 1))).length} files).`);
  }
}
